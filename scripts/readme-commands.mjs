#!/usr/bin/env node
// _CLI_FINISH_v1_ (2026-10-17): the README's command list is the command table, generated, never typed. Every usage line of every
// command (the same lines `taifoon help` prints) between the markers below; --check exits 1 when the README differs (npm test runs it).
//   node scripts/readme-commands.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { commands } from '../src/commands/index.mjs';

const FILE = new URL('../README.md', import.meta.url);
const BEGIN = '<!-- commands:begin (generated by scripts/readme-commands.mjs from the command table; do not edit) -->';
const END = '<!-- commands:end -->';
const esc = (s) => String(s).replace(/\|/g, '\\|');
const ORDER = ['login', 'logout', 'whoami', 'balance', 'buy', 'keys', 'stream', 'match', 'rpc', 'demand', 'register', 'collaborate', 'pools', 'markets', 'metrics'];

export async function block() {
  const t = await commands();
  const names = [...ORDER.filter((x) => t.has(x)), ...[...t.keys()].filter((x) => !ORDER.includes(x) && !t.get(x).admin).sort()];
  const rows = [];
  for (const n of names) {
    const c = t.get(n);
    rows.push(`| **${esc(c.name)}** | ${esc(c.summary)} |`);
    for (const [u, d] of c.usage ?? []) rows.push(`| \`taifoon ${esc(u)}\` | ${esc(d)} |`);
  }
  return [BEGIN, '', `${names.length} commands, ${rows.length - names.length} usage lines. \`taifoon <command> --help\` prints one command's lines.`, '', '| command | what it does |', '|---|---|', ...rows, '', END].join('\n');
}

const readme = readFileSync(FILE, 'utf8');
const i = readme.indexOf(BEGIN); const j = readme.indexOf(END);
if (i < 0 || j < i) { console.error(`README.md has no ${BEGIN} … ${END} block`); process.exit(1); }
const next = readme.slice(0, i) + (await block()) + readme.slice(j + END.length);
if (process.argv.includes('--check')) {
  if (next !== readme) { console.error('README.md: the command list is stale: node scripts/readme-commands.mjs'); process.exit(1); }
  console.log('README.md: the command list matches the command table');
} else { writeFileSync(FILE, next); console.log('README.md: command list written'); }
